public class Main {
    public static void main(String[] args){
        // while
        int i=0;
        while(i<10){
            System.out.println("yoo");
            i++;
        }
        //do while
        do{
            i++;
            System.out.println(("hhhh"));
        }while(i<20);
        //for loop
        for(int j=0;j<10;j++){
            System.out.println(("doen"));
        }
    }
}
